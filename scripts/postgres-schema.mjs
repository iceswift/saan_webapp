import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../prisma/schema.prisma", import.meta.url);
const target = new URL("../prisma/postgresql/schema.prisma", import.meta.url);
const schema = readFileSync(source, "utf8");
if ((schema.match(/provider\s*=\s*"sqlite"/g) ?? []).length !== 1) {
  throw new Error("Expected exactly one SQLite datasource");
}
const generated = "// Generated by scripts/postgres-schema.mjs; edit prisma/schema.prisma instead.\n" +
  schema.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== generated.replaceAll("\r\n", "\n")) {
    throw new Error("PostgreSQL schema is stale: run npm run db:postgres:schema");
  }
} else {
  writeFileSync(fileURLToPath(target), generated);
}
