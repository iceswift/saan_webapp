/** loading = กำลังทำงาน: แสดงวงหมุนนำหน้าข้อความ และกดซ้ำไม่ได้ */
function Button({
  className,
  variant = "default",
  size = "default",
  loading = false,
  disabled,
  children,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants> & { loading?: boolean }) {
  return (
    <ButtonPrimitive
      data-slot="button"
      disabled={disabled || loading}
      aria-busy={loading || undefined}
      className={cn(buttonVariants({ variant, size, className }), loading && "disabled:opacity-80")}
      {...props}
    >
      {loading ? <Loader2 aria-hidden="true" className="animate-spin-fast" /> : null}
      {children}
    </ButtonPrimitive>
  )
}

export { Button, buttonVariants }
